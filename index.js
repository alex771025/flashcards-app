let currentQuestionIndex = 0;


function showCard(){
    answerText.textContent = "";
    userAnswer.value = "";
    questionText.textContent = questions[currentQuestionIndex].text;
    cardCounter.textContent = `Карта ${currentQuestionIndex + 1} от ${questions.length}`;
    
}
answerBtn.addEventListener("click", ()=> {
    answerText.textContent = questions[currentQuestionIndex].answer;
})
nextCardBtn.addEventListener("click", ()=> {
    currentQuestionIndex++
    if(currentQuestionIndex >= questions.length){
        cardCounter.textContent = "Преговорът приключи!";
        userAnswer.value = "";
        questionText.textContent = "";
        answerText.textContent = ""
        answerBtn.disabled = true;
        nextCardBtn.disabled = true;
        return;
    }
    showCard();
})

restartBtn.addEventListener("click", ()=> {
    currentQuestionIndex = 0;
    answerBtn.disabled = false;
    nextCardBtn.disabled = false;
    showCard();
})
showCard();